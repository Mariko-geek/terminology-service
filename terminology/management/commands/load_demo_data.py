class Command(BaseCommand):
    help = 'Загружает небольшой демонстрационный набор справочников.'

    def _load_version(self, refbook, version_value, start_date, rows):
        version, _ = RefBookVersion.objects.update_or_create(
            refbook=refbook,
            version=version_value,
            defaults={'start_date': start_date},
        )
        for code, value in rows:
            RefBookElement.objects.update_or_create(
                version=version,
                code=code,
                defaults={'value': value},
            )

    def handle(self, *args, **options):
        positions, _ = RefBook.objects.update_or_create(
            code='1.2.643.5.1.13.13.11.1002',
            defaults={
                'name': 'Должности медицинских и фармацевтических работников',
                'description': 'Небольшой демонстрационный фрагмент медицинского справочника.',
            },
        )
        # Даты ниже используются только как тестовая шкала start_date.
        self._load_version(positions, '10.3', date(2026, 7, 1), POSITIONS)
        self._load_version(positions, '10.4', date(2026, 8, 1), POSITIONS)
        self._load_version(positions, '10.5', date(2026, 9, 1), POSITIONS)

        mkb, _ = RefBook.objects.update_or_create(
            code='1.2.643.5.1.13.13.11.1005',
            defaults={
                'name': 'МКБ-10 — демонстрационный фрагмент',
                'description': (
                    'Небольшой набор элементов из нескольких версий. '
                    'Используется только для демонстрации версионирования.'
                ),
            },
        )
        # Даты условные: они нужны, чтобы показать выбор версии по дате из тестового задания.
        self._load_version(mkb, '2.25', date(2026, 6, 1), MKB_225)
        self._load_version(mkb, '2.26', date(2026, 7, 1), MKB_226)
        self._load_version(mkb, '2.27', date(2026, 8, 1), MKB_227)

        self.stdout.write(self.style.SUCCESS('Демонстрационные справочники загружены.'))
